package update

import (
	"strconv"
	"strings"
)

// IsVersion reports an X.Y.Z version, with an optional v.
// A suffix after - or + is allowed and ignored.
func IsVersion(s string) bool {
	_, ok := parseVersion(s)
	return ok
}

// Newer reports whether latest is a greater version than current.
// Anything that is not X.Y.Z, such as dev, is never newer or older.
func Newer(latest, current string) bool {
	l, okL := parseVersion(latest)
	c, okC := parseVersion(current)
	if !okL || !okC {
		return false
	}
	for i := range l {
		if l[i] != c[i] {
			return l[i] > c[i]
		}
	}
	return false
}

func parseVersion(s string) ([3]int, bool) {
	var v [3]int
	s = strings.TrimPrefix(strings.TrimSpace(s), "v")
	if i := strings.IndexAny(s, "-+"); i >= 0 {
		s = s[:i]
	}
	parts := strings.Split(s, ".")
	if len(parts) != 3 {
		return v, false
	}
	for i, p := range parts {
		if p == "" || strings.TrimLeft(p, "0123456789") != "" {
			return v, false
		}
		n, err := strconv.Atoi(p)
		if err != nil {
			return v, false
		}
		v[i] = n
	}
	return v, true
}
