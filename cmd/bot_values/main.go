// note heads the table file.
const note = "Generated by make bot-values (cmd/bot_values); do not edit. Value: settledScore units (ADR 033, Decision 20)."

// lootDraws are the draws a loot card's play and doing nothing are
// settled on, as the standard level settles a candidate (Decision 8.5).
const lootDraws = 6

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, os.Args[1:], os.Stderr); err != nil {
		log.Fatal(err)
	}
}

// config is the run's flags.
type config struct {
	seed     uint64
	games    int
	cap      int
	every    int
	perGame  int
	samples  int
	items    int
	draws    int
	out      string
	missing  bool
	only     map[string]bool
	progress *logger
}

// logger writes the run's log and keeps the first write error.
type logger struct {
	w   io.Writer
	err error
}

func (l *logger) printf(format string, args ...any) {
	if l.err == nil {
		_, l.err = fmt.Fprintf(l.w, format, args...)
	}
}

// run parses the flags, measures and writes the table.
func run(ctx context.Context, args []string, log io.Writer) error {
	fs := flag.NewFlagSet("bot_values", flag.ContinueOnError)
	var c config
	fs.Uint64Var(&c.seed, "seed", 1, "seed of the arena games and the samples")
	fs.IntVar(&c.games, "games", 12, "arena games of each table size (2, 3, 4 players) the positions come from")
	fs.IntVar(&c.cap, "cap", 60, "game turns the arena games play at most")
	fs.IntVar(&c.every, "every", 23, "keep about one priority position in this many steps of a game")
	fs.IntVar(&c.perGame, "per_game", 60, "positions kept of a game at most")
	fs.IntVar(&c.samples, "samples", 32, "positions a loot card is measured on at most")
	fs.IntVar(&c.items, "item_samples", 64, "positions an item is measured on at most")
	fs.IntVar(&c.draws, "draws", 4, "seeds an item is played out on, a position")
	fs.StringVar(&c.out, "out", "internal/bot/values.json", "the table file")
	fs.BoolVar(&c.missing, "missing", false, "measure only the cards the table file lacks, keep the rest")
	only := fs.String("cards", "", "measure only these cards (comma-separated refs), keep the rest")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if c.games < 1 || c.cap < 1 || c.samples < 1 || c.items < 1 || c.draws < 1 || c.every < 1 || c.perGame < 1 {
		return errors.New("bot_values: -games, -cap, -samples, -item_samples, -draws, -every and -per_game must be at least 1")
	}
	if *only != "" {
		c.only = map[string]bool{}
		for s := range strings.SplitSeq(*only, ",") {
			c.only[strings.TrimSpace(s)] = true
		}
	}
	lg := &logger{w: log}
	c.progress = lg
	old := bot.ValueFile{}
	if c.missing || c.only != nil {
		data, err := os.ReadFile(c.out)
		if err != nil {
			return err
		}
		if old, err = bot.ParseValues(data); err != nil {
			return err
		}
	}
	jobs := todo(allCards(), old, c)
	start := time.Now()
	lg.printf("bot_values: %d cards to measure on %d cores\n", len(jobs), runtime.GOMAXPROCS(0))
	if len(jobs) == 0 {
		return lg.err
	}
	pos, err := positions(ctx, c)
	if err != nil {
		return err
	}
	lg.printf("bot_values: %d positions from %d games in %s\n", len(pos), 3*c.games, time.Since(start).Round(time.Second))
	got, err := measureAll(ctx, jobs, pos, c)
	if err != nil {
		return err
	}
	f := merge(old, got, c)
	data, err := encode(f)
	if err != nil {
		return err
	}
	if err := os.WriteFile(c.out, data, 0o644); err != nil { //nolint:gosec // a source file of the repo
		return err
	}
	lg.printf("bot_values: %d cards in %s; wrote %s\n", len(jobs), time.Since(start).Round(time.Second), c.out)
	summary(lg, got)
	return lg.err
}

// card is one value to measure: a card as loot in hand or as an item.
type card struct {
	ref  engine.CardRef
	kind string // bot.KindLoot, KindActive or KindPassive
	deck engine.DeckKind
}

// item: the card is measured in play.
func (c card) item() bool { return c.kind != bot.KindLoot }

// allCards are the loot cards and items of every set, each once, in a
// fixed order: loot in hand; treasure and trinkets in play. A card that
// starts outside the game (a starting item) is in no deck and falls back
// to its kind's mean.
func allCards() []card {
	seen := map[card]bool{}
	var out []card
	add := func(c card) {
		if !seen[c] {
			seen[c] = true
			out = append(out, c)
		}
	}
	for _, s := range cards.Sets() {
		for _, d := range s.Cards {
			if d.Outside {
				continue
			}
			item := bot.KindPassive
			if d.Tap {
				item = bot.KindActive
			}
			switch d.Kind {
			case engine.LootCard:
				add(card{ref: d.Ref, kind: bot.KindLoot, deck: engine.LootDeck})
				if d.Trinket {
					add(card{ref: d.Ref, kind: item, deck: engine.LootDeck})
				}
			case engine.TreasureCard:
				add(card{ref: d.Ref, kind: item, deck: engine.TreasureDeck})
			default: // other kinds have no value
			}
		}
	}
	return out
}

// todo are the cards to measure: all, or with -missing those the old
// table lacks, or with -cards those named. Items first: they cost most.
func todo(all []card, old bot.ValueFile, c config) []card {
	have := map[[2]string]bool{}
	for _, e := range old.Cards {
		have[[2]string{e.Key, e.Kind}] = true
	}
	var out []card
	for _, x := range all {
		switch {
		case c.only != nil && !c.only[string(x.ref)]:
			continue
		case c.only == nil && c.missing && have[[2]string{string(x.ref), x.kind}]:
			continue
		}
		out = append(out, x)
	}
	slices.SortStableFunc(out, func(a, b card) int {
		switch {
		case a.item() && !b.item():
			return -1
		case !a.item() && b.item():
			return 1
		}
		return 0
	})
	return out
}

// position is a kept game state and the seat to move in it.
type position struct {
	g *engine.Game
	p engine.PlayerID
}

// positions plays the arena games of the flat level, games of 2, 3 and
// 4 players side by side, and keeps about one priority position in
// c.every steps of each, at most c.perGame, in game order (Decision
// 20.4.8).
func positions(ctx context.Context, c config) ([]position, error) {
	const sizes = 3 // 2, 3 and 4 players
	kept := make([][][]position, sizes)
	errs := make([]error, sizes)
	var wg sync.WaitGroup
	for i := range sizes {
		seats := i + 2
		kept[i] = make([][]position, c.games)
		var mu sync.Mutex
		var copyErrs []error
		m := arena.Match{
			Levels: slices.Repeat([]bot.Level{bot.Flat}, seats),
			Games:  c.games,
			Cap:    c.cap,
			Seed:   c.seed + uint64(seats)*1000, //nolint:gosec // seats is 2 to 4
			Watch: func(k, step int, g *engine.Game) {
				pr := g.Prompt()
				if pr.Kind != engine.PromptPriority || len(kept[i][k]) >= c.perGame || mix(c.seed, uint64(seats), uint64(k), uint64(step))%uint64(c.every) != 0 { //nolint:gosec // small counts
					return
				}
				cp, err := g.Clone()
				if err != nil {
					mu.Lock()
					copyErrs = append(copyErrs, err)
					mu.Unlock()
					return
				}
				kept[i][k] = append(kept[i][k], position{g: cp, p: pr.Who()[0]})
			},
		}
		wg.Go(func() {
			_, err := arena.Play(ctx, m)
			errs[i] = errors.Join(err, errors.Join(copyErrs...))
		})
	}
	wg.Wait()
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	if ctx.Err() != nil {
		return nil, ctx.Err()
	}
	var out []position
	for _, games := range kept {
		for _, ps := range games {
			out = append(out, ps...)
		}
	}
	return out, nil
}

// mix hashes a few numbers into one (SplitMix64 steps).
func mix(xs ...uint64) uint64 {
	z := uint64(0x9e3779b97f4a7c15)
	for _, x := range xs {
		z ^= x + 0x9e3779b97f4a7c15 + (z << 6) + (z >> 2)
		z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
		z = (z ^ (z >> 27)) * 0x94d049bb133111eb
		z ^= z >> 31
	}
	return z
}

// measured is one card's result.
type measured struct {
	card
	xs []float64 // one value a position
	// uses are an active item's gains of a use over doing nothing,
	// where it may be used (Decision 20.4.10).
	uses []float64
}

// measureAll measures the cards side by side on every core; the result
// is in the order of jobs and does not depend on the cores.
func measureAll(ctx context.Context, jobs []card, pos []position, c config) ([]measured, error) {
	out := make([]measured, len(jobs))
	errs := make([]error, len(jobs))
	next := make(chan int)
	var wg sync.WaitGroup
	var mu sync.Mutex
	done := 0
	for range min(runtime.GOMAXPROCS(0), len(jobs)) {
		wg.Go(func() {
			for i := range next {
				out[i] = measured{card: jobs[i]}
				out[i].xs, out[i].uses, errs[i] = measure(jobs[i], pos, c)
				mu.Lock()
				done++
				c.progress.printf("  %d/%d %s %s: %d samples, %d uses\n", done, len(jobs), jobs[i].kind, jobs[i].ref, len(out[i].xs), len(out[i].uses))
				mu.Unlock()
			}
		})
	}
	for i := range jobs {
		if ctx.Err() != nil {
			break
		}
		next <- i
	}
	close(next)
	wg.Wait()
	if ctx.Err() != nil {
		return nil, ctx.Err()
	}
	return out, errors.Join(errs...)
}

// measure is card x's value on each position it is measured on, up to
// c.samples for loot and c.items for an item: the positions in an order
// of the card's own, those where the card lies in its deck, and for
// loot those where the seat may play it. For an active item, uses are
// also the gains of using it over doing nothing, where the seat may.
func measure(x card, pos []position, c config) (xs, uses []float64, err error) {
	h := fnv.New64a()
	_, _ = h.Write([]byte(x.kind + " " + string(x.ref)))
	rng := rand.New(rand.NewPCG(c.seed, h.Sum64())) //nolint:gosec // samples, not security
	want := c.samples
	if x.item() {
		want = c.items
	}
	for _, i := range rng.Perm(len(pos)) {
		if len(xs) >= want {
			break
		}
		ps := pos[i]
		id, ok := inDeck(ps.g, x)
		if !ok {
			continue
		}
		with, err := ps.g.Clone()
		if err != nil {
			return nil, nil, err
		}
		nid, err := enginetest.PlaceFromDeck(with, id, ps.p, x.item())
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", x.ref, err)
		}
		seeds := make([]uint64, max(c.draws, lootDraws))
		for k := range seeds {
			seeds[k] = rng.Uint64()
		}
		if !x.item() || x.kind == bot.KindActive {
			gain, ok, err := bot.PlayGain(fixed(with), ps.p, nid, seeds[:lootDraws])
			if err != nil {
				return nil, nil, fmt.Errorf("%s: %w", x.ref, err)
			}
			switch {
			case ok && !x.item():
				xs = append(xs, max(0, gain))
			case ok:
				uses = append(uses, max(0, gain))
			}
			if !x.item() {
				continue
			}
		}
		sum := 0.0
		for _, s := range seeds[:c.draws] {
			a, err := bot.ItemPlayout(fixed(with), ps.p, s)
			if err != nil {
				return nil, nil, fmt.Errorf("%s: %w", x.ref, err)
			}
			b, err := bot.ItemPlayout(fixed(ps.g), ps.p, s)
			if err != nil {
				return nil, nil, fmt.Errorf("%s: %w", x.ref, err)
			}
			sum += min(max(a-b, -bot.ValueClip), bot.ValueClip)
		}
		xs = append(xs, sum/float64(c.draws))
	}
	return xs, uses, nil
}

// fixed is a world that is always g: the measure plays on the kept
// position itself, not on a seat's guess of it. The bot copies a world
// before it plays on it.
func fixed(g *engine.Game) bot.World {
	return func(int) (*engine.Game, error) { return g, nil }
}

// inDeck is the object of card x in its deck on g: the topmost copy.
func inDeck(g *engine.Game, x card) (engine.ObjectID, bool) {
	deck := g.Decks[x.deck]
	for i := len(deck) - 1; i >= 0; i-- {
		if g.Object(deck[i]).Card == x.ref {
			return deck[i], true
		}
	}
	return 0, false
}

// merge puts the measured cards into the old table: a measured card
// replaces its old entry. The entries are sorted by kind, then card.
func merge(old bot.ValueFile, got []measured, c config) bot.ValueFile {
	f := bot.ValueFile{Note: note, Seed: c.seed, Games: c.games, Samples: c.samples, ItemSamples: c.items}
	idx := map[[2]string]int{}
	for _, e := range old.Cards {
		idx[[2]string{e.Key, e.Kind}] = len(f.Cards)
		f.Cards = append(f.Cards, e)
	}
	for _, m := range got {
		e := entry(m)
		if i, ok := idx[[2]string{e.Key, e.Kind}]; ok {
			f.Cards[i] = e
			continue
		}
		f.Cards = append(f.Cards, e)
	}
	order := map[string]int{bot.KindLoot: 0, bot.KindActive: 1, bot.KindPassive: 2}
	slices.SortFunc(f.Cards, func(a, b bot.ValueEntry) int {
		if d := order[a.Kind] - order[b.Kind]; d != 0 {
			return d
		}
		return strings.Compare(a.Key, b.Key)
	})
	return f
}

// entry is a card's table entry: the mean of its samples and their
// standard error, rounded so the file stays readable. An active item
// takes the larger of its two measures, the playouts and the uses
// (Decision 20.4.10).
func entry(m measured) bot.ValueEntry {
	e := bot.ValueEntry{Key: string(m.ref), Kind: m.kind, Measure: bot.MeasurePlay}
	if m.item() {
		e.Measure = bot.MeasurePlayout
	}
	e.Value, e.SE, e.N = stats(m.xs)
	if v, se, n := stats(m.uses); n > 0 && (e.N == 0 || v > e.Value) {
		e.Value, e.SE, e.N, e.Measure = v, se, n, bot.MeasureUse
	}
	return e
}

// stats are the rounded mean of xs, its standard error and the count.
func stats(xs []float64) (mean, se float64, n int) {
	n = len(xs)
	if n == 0 {
		return 0, 0, 0
	}
	sum := 0.0
	for _, x := range xs {
		sum += x
	}
	m := sum / float64(n)
	ss := 0.0
	for _, x := range xs {
		ss += (x - m) * (x - m)
	}
	if n > 1 {
		se = round(math.Sqrt(ss / float64(n-1) / float64(n)))
	}
	return round(m), se, n
}

// round keeps three decimals.
func round(x float64) float64 { return math.Round(x*1000) / 1000 }

// encode writes the table file: one card a line.
func encode(f bot.ValueFile) ([]byte, error) {
	cardsJSON := f.Cards
	f.Cards = nil
	head, err := json.Marshal(f)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	// The head without its closing "Cards":null}, then the cards.
	b.Write(bytes.TrimSuffix(head, []byte(`"Cards":null}`)))
	b.WriteString("\"Cards\":[\n")
	for i, e := range cardsJSON {
		line, err := json.Marshal(e)
		if err != nil {
			return nil, err
		}
		b.Write(line)
		if i < len(cardsJSON)-1 {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteString("]}\n")
	return b.Bytes(), nil
}

// summary prints, per kind, the mean value, the median standard error,
// and the cards with too few samples.
func summary(w *logger, got []measured) {
	for _, kind := range []string{bot.KindLoot, bot.KindActive, bot.KindPassive} {
		var vals, ses []float64
		none := 0
		for _, m := range got {
			if m.kind != kind {
				continue
			}
			e := entry(m)
			if e.N == 0 {
				none++
				continue
			}
			vals = append(vals, e.Value)
			if e.N > 1 {
				ses = append(ses, e.SE)
			}
		}
		if len(vals) == 0 {
			continue
		}
		slices.Sort(ses)
		med := 0.0
		if len(ses) > 0 {
			med = ses[len(ses)/2]
		}
		sum := 0.0
		for _, v := range vals {
			sum += v
		}
		w.printf("  %-7s %d cards, mean %.2f, median standard error %.2f, %d with no sample\n", kind, len(vals), sum/float64(len(vals)), med, none)
	}
}
