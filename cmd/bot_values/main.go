// Command bot_values measures what each loot card and item is worth to
// the bots and writes the table the score reads (ADR 033, Decision 20):
//
//	bot_values                  # every card: make bot-values
//	bot_values -missing         # only the cards the table lacks: a new set
//
// It plays arena games of the flat level (standard with every card worth
// alike), keeps positions of them, and measures each card on a sample of
// those positions, put into a copy by enginetest.PlaceFromDeck:
//
//   - a loot card in the hand of the seat to move: where the seat may
//     play it, the gain of its best play over doing nothing, both settled
//     as the standard level settles, on common draws; less than nothing
//     counts 0 (Decision 20.4.1 – 20.4.4);
//   - an item in play under that seat: the copy with it against the copy
//     without, each played out by the policy to the end of the seat's
//     next turn on common seeds (Decision 20.4.5 – 20.4.7); an active
//     item also as loot is, by its uses, and the larger counts (Decision
//     20.4.10).
//
// Each paired difference counts at most one soul either way
// (bot.ValueClip, Decision 20.4.9).
//
// Both score with the flat values: one pass, no iterations (Decision
// 20.6). The same seed and cards give the same file. Games run side by
// side, then cards, on every core.
